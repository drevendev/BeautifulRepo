#!/usr/bin/env python3
"""Describe and checksum the actual browser capture of the fictional audit demo.

This validates source markers and PNG headers; it does not visually inspect pixels,
certify accessibility, or prove an actual user's repository was improved.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import struct
import sys

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
EXPECTED_MARKERS = (
    "Synthetic Pocket Trails fixture.",
    "0/2 local-link checks pass.",
    "2/2 local-link checks pass.",
    "-Read the [setup guide](docs/setup.md)",
    "+Read the [setup guide](docs/guide.md)",
)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _png_dimensions(path: Path) -> tuple[int, int]:
    with path.open("rb") as source:
        header = source.read(24)
    if (len(header) != 24 or header[:8] != PNG_SIGNATURE
            or header[12:16] != b"IHDR"
            or struct.unpack(">I", header[8:12])[0] != 13):
        raise ValueError(f"{path.name}: invalid PNG signature/IHDR")
    width, height = struct.unpack(">II", header[16:24])
    if not (320 <= width <= 2560 and 320 <= height <= 2560):
        raise ValueError(f"{path.name}: unexpected PNG dimensions {width}x{height}")
    return width, height


def render_evidence(folder: Path, revision: str | None) -> str:
    """Return a truthful text companion for a completed synthetic capture."""
    if revision is not None and not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("--revision must be an exact 40-character lowercase Git SHA")
    html_file = folder / "report.html"
    if html_file.stat().st_size > 2_000_000:
        raise ValueError("report.html exceeds the 2 MB evidence limit")
    html = html_file.read_text(encoding="utf-8")
    if not html.startswith("<!doctype html>"):
        raise ValueError("report.html is not the expected generated document")
    for marker in EXPECTED_MARKERS:
        if marker not in html:
            raise ValueError(f"report.html is missing a required synthetic marker: {marker}")

    images = {name: folder / (name + ".png") for name in ("desktop", "mobile")}
    dimensions = {name: _png_dimensions(file) for name, file in images.items()}
    revision_text = f"`{revision}` (checked-out commit)" if revision else "not recorded"
    hashes = [(p.name, _sha256(p)) for p in (html_file, *images.values())]
    return (
        "# Pocket Trails — synthetic browser evidence\n\n"
        "**Fixture:** fictional Pocket Trails; not a real repository repair or a user session.\n\n"
        f"**Source checkout:** {revision_text}.\n\n"
        "**Source-derived observations:** before, 0/2 local-link checks pass "
        "(combined exit 1); after, 2/2 pass (combined exit 0). "
        "One fictional README destination changes from `docs/setup.md` "
        "(missing) to `docs/guide.md` (present). "
        "The numbers and diff are checked against `report.html`, which was "
        "generated by the actual offline checkers on disposable fixtures.\n\n"
        "**Text alternative for the captures:** the report opens with the "
        "heading *One broken link, two independent checkers*, a conspicuous "
        "synthetic-fixture disclosure, and separate Before (0/2) and After "
        "(2/2) result boxes ahead of the one-line README diff and detailed "
        "diagnostics. This describes the report's authored content, not "
        "an independently verified pixel reading.\n\n"
        "**PNG dimensions read from image headers** (not a physical device "
        "or CSS viewport measurement):\n\n"
        f"- `desktop.png`: {dimensions['desktop'][0]}×{dimensions['desktop'][1]} pixels\n"
        f"- `mobile.png`: {dimensions['mobile'][0]}×{dimensions['mobile'][1]} pixels\n\n"
        "**SHA-256 checksums** (verify the three files travel together):\n\n"
        + "".join(f"- `{name}`: `{digest}`\n" for name, digest in hashes)
        + "\n**Reproduce from this checkout** (Python 3.11+, installed Chrome/Chromium):\n\n"
        "```bash\n"
        "python -I examples/combined-audit/capture.py --output-dir ../beautifulrepo-audit-capture\n"
        "python -I examples/combined-audit/evidence.py ../beautifulrepo-audit-capture\n"
        "```\n\n"
        "**Limits:** the check confirms source markers, PNG header dimensions "
        "and file hashes. It does not decode/visually review PNG pixels, verify "
        "effective browser viewport, test keyboard/screen-reader behavior, "
        "prove source authenticity beyond the named checkout, or imply real "
        "repository/user outcomes. Manually inspect the actual images and "
        "HTML before publishing. CI artifacts expire after seven days.\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("folder", type=Path, help="directory containing report.html and both PNG captures")
    parser.add_argument("--revision", help="optional exact checked-out 40-character Git commit SHA")
    args = parser.parse_args(argv)
    destination = args.folder / "evidence.md"
    try:
        if destination.exists():
            raise ValueError("evidence.md already exists; refusing to overwrite")
        rendered = render_evidence(args.folder, args.revision)
        with destination.open("x", encoding="utf-8", newline="\n") as output:
            output.write(rendered)
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"Evidence incomplete: {exc}", file=sys.stderr)
        return 2
    print(destination)
    print("Synthetic fixture only; independently inspect the captures before reuse.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
